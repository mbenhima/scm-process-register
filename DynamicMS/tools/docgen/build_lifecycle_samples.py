"""Packs the lifecycle sample documents of the universal scenario (rendered by
server/tools/render-lifecycle-samples.mjs into deliverables/build/lifecycle-<lang>) into one zip
per language, with an index workbook (AI Value graphical chart): one line per document with its
end-to-end process, PDCA stage, folder, code, title, type, version, status and formats.
Usage: python3 build_lifecycle_samples.py [en|fr|all]"""
import json
import os
import sys
import zipfile

from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BUILD = os.path.join(ROOT, 'deliverables', 'build')
OUT = os.path.join(ROOT, 'deliverables')
NAVY, AZURE, INK, MUTED, BG, LINE = '123A5F', '1876C6', '2C3E50', '5A6B7B', 'F5F8FB', 'E1E8F0'
PDCA = {'E2E-01': 'P', 'E2E-02': 'P', 'E2E-03': 'P', 'E2E-04': 'P', 'E2E-05': 'D', 'E2E-06': 'D', 'E2E-07': 'D', 'E2E-08': 'D', 'E2E-09': 'C', 'E2E-10': 'C', 'E2E-11': 'C', 'E2E-12': 'A'}
W = {
    'en': dict(title='Sample documents generated by DynamicMS — one full lifecycle', sub='Universal scenario, any sector: {p}. One folder per end-to-end process (E2E-01 to E2E-12) and a Reports folder.', sheet='Index',
               cols=['End-to-end process', 'PDCA', 'Folder', 'Code', 'Title', 'Type', 'Version', 'Status', 'Formats'],
               pdca={'P': 'Plan', 'D': 'Do', 'C': 'Check', 'A': 'Act', '': 'Reports'}, rep='Reports (all phases)',
               note='Documents are rendered from the live project data with the document templates of DynamicMS; reports are exported in PDF, Word, Excel, PowerPoint and CSV.'),
    'fr': dict(title='Exemples de documents générés par DynamicMS — un cycle de vie complet', sub='Scénario universel, tout secteur : {p}. Un dossier par processus de bout en bout (E2E-01 à E2E-12) et un dossier Rapports.', sheet='Index',
               cols=['Processus de bout en bout', 'PDCA', 'Dossier', 'Code', 'Titre', 'Type', 'Version', 'Statut', 'Formats'],
               pdca={'P': 'Planifier', 'D': 'Réaliser', 'C': 'Vérifier', 'A': 'Agir', '': 'Rapports'}, rep='Rapports (toutes phases)',
               note='Les documents sont produits à partir des données réelles du projet avec les modèles de documents de DynamicMS ; les rapports sont exportés en PDF, Word, Excel, PowerPoint et CSV.'),
}


def index_xlsx(data, lang, path):
    w = W[lang]
    wb = Workbook(); ws = wb.active; ws.title = w['sheet']
    ws.sheet_view.showGridLines = False
    ws['A1'] = 'DYNAMICMS · AI VALUE'; ws['A1'].font = Font(name='Open Sans', bold=True, size=10, color=AZURE)
    ws['A2'] = w['title']; ws['A2'].font = Font(name='Montserrat', bold=True, size=16, color=NAVY)
    ws['A3'] = w['sub'].format(p=f"{data['project']['code']} — {data['project']['name']}"); ws['A3'].font = Font(name='Open Sans', size=10, color=MUTED)
    ws['A4'] = w['note']; ws['A4'].font = Font(name='Open Sans', italic=True, size=9, color=MUTED)
    hdr = 6
    thin = Side(style='thin', color=LINE)
    for i, c in enumerate(w['cols'], 1):
        cell = ws.cell(row=hdr, column=i, value=c)
        cell.font = Font(name='Open Sans', bold=True, size=10, color='FFFFFF'); cell.fill = PatternFill('solid', fgColor=NAVY)
        cell.alignment = Alignment(vertical='center', wrap_text=True); cell.border = Border(bottom=thin)
    order = lambda it: (it['phase'] == 'REPORTS', it['phase'], it['code'])
    for r, it in enumerate(sorted(data['items'], key=order), hdr + 1):
        rep = it['phase'] == 'REPORTS'
        vals = [w['rep'] if rep else f"{it['phase']} {it['phaseName']}", w['pdca'][PDCA.get(it['phase'], '')], it['folder'], it['code'], it['title'], it['type'], it['version'], it['status'], ', '.join(it['formats'])]
        for i, v in enumerate(vals, 1):
            cell = ws.cell(row=r, column=i, value=v)
            cell.font = Font(name='Open Sans', size=9.5, color=INK, bold=(i == 4))
            cell.alignment = Alignment(vertical='top', wrap_text=True)
            cell.fill = PatternFill('solid', fgColor='FFFFFF' if (r - hdr) % 2 else BG)
            cell.border = Border(bottom=thin)
    for i, wd in enumerate([30, 11, 34, 26, 48, 12, 9, 12, 22], 1):
        ws.column_dimensions[chr(64 + i)].width = wd
    ws.freeze_panes = ws.cell(row=hdr + 1, column=1)
    ws.auto_filter.ref = f"A{hdr}:I{hdr + len(data['items'])}"
    wb.save(path)


def build(lang):
    src = os.path.join(BUILD, f'lifecycle-{lang}')
    data = json.load(open(os.path.join(src, 'index.json'), encoding='utf8'))
    idx = os.path.join(src, f'00_Index_{lang.upper()}.xlsx')
    index_xlsx(data, lang, idx)
    out = os.path.join(OUT, f'DynamicMS_Sample_IMS_Documents_{lang.upper()}.zip')
    top = f'DynamicMS_Sample_IMS_Documents_{lang.upper()}'
    n = 0
    with zipfile.ZipFile(out, 'w', zipfile.ZIP_DEFLATED) as z:
        for base, _, files in os.walk(src):
            for f in sorted(files):
                if f == 'index.json':
                    continue
                full = os.path.join(base, f)
                z.write(full, os.path.join(top, os.path.relpath(full, src)))
                n += 1
    print(out, n, 'files', round(os.path.getsize(out) / 1e6, 1), 'MB')


if __name__ == '__main__':
    which = sys.argv[1] if len(sys.argv) > 1 else 'all'
    for lg in (['en', 'fr'] if which == 'all' else [which]):
        build(lg)
